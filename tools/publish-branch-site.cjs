#!/usr/bin/env node
/**
 * Publish the static preview from the branch itself.
 *
 * GitHub Pages is configured as "Deploy from a branch" pointing at this branch,
 * so whatever sits at the branch root is published. That is how the preview gets
 * online without anyone having to change a setting - but it has two hazards this
 * script handles:
 *
 *   1. `.env` (APP_KEY, DB credentials) and `database/mmheritagehotel_db.sql`
 *      (172 tables of production rows) are tracked. Jekyll ignores dotfiles and
 *      `_config.yml` excludes the rest of the tree, so neither is published.
 *   2. `public/assets`, `public/frontend` and `public/food_menu` are already in
 *      the repository. Copying the export's 23 MB duplicate would be waste, so
 *      page URLs are rewritten to point at the existing files instead.
 *
 * Usage: node tools/publish-branch-site.cjs [--dry-run]
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist-preview');
const MANIFEST = path.join(ROOT, '.pages-publish-manifest.json');
const DRY = process.argv.includes('--dry-run');

// Trees that already exist in the repository under public/.
const ASSET_TREES = ['assets', 'frontend', 'food_menu'];
// Files the exporter writes for the standalone artifact, not for a branch publish.
const SKIP_FILES = ['.nojekyll', 'export-manifest.json'];

const REWRITE = /(?<![\w\-/])((?:\.\.\/)*)(assets|frontend|food_menu)\//g;
const TEXT = /\.(html|css|js|json|txt|xml|svg|map)$/i;

if (!fs.existsSync(DIST)) {
    console.error('No export at dist-preview - run tools/export-static-preview.cjs first.');
    process.exit(1);
}

const previous = fs.existsSync(MANIFEST) ? new Set(JSON.parse(fs.readFileSync(MANIFEST, 'utf8'))) : new Set();
const written = [];
const skippedStale = [];
let missing = 0;

function walk(dir, out = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full, out);
        else out.push(full);
    }
    return out;
}

// --- 1. Copy the site pages, rewriting asset roots to public/ ---------------
const distFiles = walk(DIST);
for (const file of distFiles) {
    const rel = path.relative(DIST, file);
    const [top] = rel.split(path.sep);
    if (ASSET_TREES.includes(top) || SKIP_FILES.includes(top)) continue;

    let body = fs.readFileSync(file);
    if (TEXT.test(rel)) {
        const original = body.toString('utf8');
        // Fixtures emit paths like ../.././assets/... after url() folding; drop the
        // redundant segment so the asset rewrite below can see the tree name.
        const normalised = original.replace(/\/\.(?=\/)/g, '');
        const rewritten = normalised.replace(REWRITE, '$1public/$2/');
        if (rewritten !== original) body = Buffer.from(rewritten, 'utf8');
    }

    const target = path.join(ROOT, rel);
    if (fs.existsSync(target) && !previous.has(rel) && !fs.existsSync(MANIFEST)) {
        console.error('refusing to overwrite a repository file: ' + rel);
        process.exit(1);
    }
    if (!DRY) {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, body);
    }
    written.push(rel);
}

// Files written previously that this export no longer produces.
for (const rel of previous) {
    if (written.includes(rel)) continue;
    const target = path.join(ROOT, rel);
    if (fs.existsSync(target)) {
        if (!DRY) fs.unlinkSync(target);
        skippedStale.push(rel);
    }
}

// --- 2. Asset stand-ins the export generated, that public/ lacks -----------
const standIns = [];
for (const tree of ASSET_TREES) {
    const from = path.join(DIST, tree);
    if (!fs.existsSync(from)) continue;
    for (const file of walk(from)) {
        const rel = path.relative(DIST, file);
        const target = path.join(ROOT, 'public', rel);
        if (fs.existsSync(target)) continue;
        if (!DRY) {
            fs.mkdirSync(path.dirname(target), { recursive: true });
            fs.copyFileSync(file, target);
        }
        standIns.push(rel);
    }
}

// --- 3. robots.txt: a demo, not a site to index ----------------------------
const robots = 'User-agent: *\nDisallow: /\n';
if (!DRY) fs.writeFileSync(path.join(ROOT, 'robots.txt'), robots);
if (!written.includes('robots.txt')) written.push('robots.txt');

// --- 4. Jekyll config: publish the site, exclude the repository ------------
const keep = new Set(['public', '_config.yml', ...written.map((p) => p.split(path.sep)[0])]);
// Never publish application entry points even though public/ is served.
const EXTRA_EXCLUDES = ['public/index.php', 'public/.htaccess'];
const excluded = fs.readdirSync(ROOT)
    .filter((name) => !keep.has(name))
    .concat(EXTRA_EXCLUDES)
    .sort();
const config = [
    '# Generated by tools/publish-branch-site.cjs - do not edit by hand.',
    '#',
    '# GitHub Pages builds this branch (Source: "Deploy from a branch"). Jekyll',
    '# copies the exported preview at the root and must not touch the application:',
    '# .env is skipped because Jekyll ignores dotfiles, and everything else is',
    '# listed below. database/ matters most - it holds the production-sized dump.',
    'exclude:',
    ...excluded.map((name) => '  - ' + JSON.stringify(name)),
    '',
].join('\n');
if (!DRY) fs.writeFileSync(path.join(ROOT, '_config.yml'), config);

// --- 5. Verify every relative reference resolves --------------------------
// Same shape as tools/check-static-preview.cjs: a quoted value stops at the
// first quote, which is exactly what skips inline JS such as href="'+url+'/".
const refs = /\b(?:href|src|poster)\s*=\s*["']([^"']*)["']/gi;
const broken = [];
for (const rel of written) {
    if (!/\.html$/.test(rel)) continue;
    const body = fs.readFileSync(path.join(ROOT, rel), 'utf8');
    for (const m of body.matchAll(refs)) {
        const value = (m[1] || '').trim();
        if (!value || value.startsWith('#') || value.startsWith('data:')) continue;
        if (value.startsWith('javascript:')) continue;
        if (/^(https?:)?\/\//i.test(value)) continue;
        if (/^(mailto|tel):/i.test(value)) continue;

        const cut = value.search(/[?#]/);
        const clean = cut >= 0 ? value.slice(0, cut) : value;
        if (!clean) continue;
        const resolved = path.resolve(path.dirname(path.join(ROOT, rel)), clean);
        if (!resolved.startsWith(ROOT)) {
            broken.push(rel + ' -> escapes the repository: ' + value);
        } else if (!(fs.existsSync(resolved) && fs.statSync(resolved).isFile())
            && !fs.existsSync(path.join(resolved, 'index.html'))) {
            broken.push(rel + ' -> ' + value);
        }
    }
}

// --- report ---------------------------------------------------------------
const bytes = written.reduce((sum, rel) => {
    const full = path.join(ROOT, rel);
    return sum + (fs.existsSync(full) ? fs.statSync(full).size : 0);
}, 0);

console.log('published ' + written.length + ' page files (' + (bytes / 1048576).toFixed(1) + ' MB) to the branch root');
console.log('asset stand-ins copied into public/: ' + (standIns.length ? standIns.join(', ') : 'none'));
console.log('excluded from the Jekyll build: ' + excluded.length + ' top-level entries');
console.log('broken references: ' + broken.length);
broken.slice(0, 15).forEach((b) => console.log('  ' + b));

if (!DRY) fs.writeFileSync(MANIFEST, JSON.stringify(written.sort(), null, 2) + '\n');
if (broken.length) process.exit(1);
console.log(DRY ? 'PUBLISH_DRY_RUN_OK' : 'PUBLISH_OK');
